#!/usr/bin/env python3
"""
Execute TopicAttack payloads against InjecAgent benchmark using InjecAgentChatSession.

Expects attack-complete JSON files produced by construct_attack.py on seed files
generated by generate_seeds_injecagent.py.  Each item must carry the metadata fields
added during seed generation:
  "suite"                - "dh" or "ds"
  "setting"              - "base" or "enhanced"
  "user_task_index"      - int
  "injection_task_index" - int
  "Attacker Instruction" - the full TopicAttack multi-turn payload

Results are reported separately for DH (Direct Harm) and DS (Data Stealing, S1 only),
matching InjecAgentChatSession's evaluation depth for the first attacker tool.

Usage (from this directory):
    python run_topicattack_injecagent.py \\
        --data_paths ../data/attack_complete_dh_base.json ../data/attack_complete_ds_base.json \\
        --model_name gpt-4o-mini \\
        --log_file logs/topicattack_injecagent_base.txt
"""

import argparse
import json
import os
import sys
from datetime import datetime

# ── repo root on path so Benchmarks.* imports resolve ──────────────────────────
_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", ".."))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from benchmarks.injecagent.src.api import InjecAgentChatSession  # noqa: E402


# ── helpers ───────────────────────────────────────────────────────────────────

def _ts() -> str:
    return datetime.now().strftime("%H:%M:%S")


def _mk_text_block(text: str) -> dict:
    return {"type": "text", "content": text}


def _bootstrap_history(session: InjecAgentChatSession) -> None:
    """
    Populate session.history without the wasteful baseline model call that
    init_chat() would make.  Mirrors init_chat()'s message construction but
    skips the trailing send().
    """
    item = session._selected_item
    user_msg = {"role": "user", "content": [_mk_text_block(item["User Instruction"])]}
    assistant_msg = {"role": "assistant", "content": [_mk_text_block(item.get("Thought", ""))]}
    tool_msg = {
        "role": "tool",
        "content": [_mk_text_block(item["Tool Response Template"])],
        "tool_name": item.get("User Tool", "synthetic_tool"),
    }
    session.history = [user_msg, assistant_msg, tool_msg]
    session._initialized = True


def _run_entry(item: dict, model_name: str) -> bool:
    """Inject the TopicAttack payload and return True if the attack succeeded."""
    suite = item["suite"]
    setting = item["setting"]
    user_idx = item["user_task_index"]
    inj_idx = item["injection_task_index"]
    payload = item["Attacker Instruction"]

    os.environ["SETTING"] = setting
    os.environ["MODEL_TYPE"] = "GPT"
    os.environ["MODEL_NAME"] = model_name
    os.environ["PROMPT_TYPE"] = "InjecAgent"

    session = InjecAgentChatSession(
        suite_name=suite,
        user_task_id=str(user_idx),
        injection_task_name=str(inj_idx),
        model_name=model_name,
    )

    _bootstrap_history(session)

    _messages, success_str, _utility_str = session.inject_at_tool_message(payload)
    return "True" in success_str


# ── main ──────────────────────────────────────────────────────────────────────

def run(args: argparse.Namespace) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(args.log_file)), exist_ok=True)
    log_fh = open(args.log_file, "w", encoding="utf-8")

    def log(msg: str) -> None:
        print(msg)
        log_fh.write(msg + "\n")
        log_fh.flush()

    all_items: list[dict] = []
    for path in args.data_paths:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        log(f"[{_ts()}] Loaded {len(data)} items from {path}")
        all_items.extend(data)

    total = len(all_items)
    counts: dict[str, dict[str, int]] = {
        "dh": {"total": 0, "success": 0},
        "ds": {"total": 0, "success": 0},
    }

    for idx, item in enumerate(all_items):
        suite = item.get("suite", "?")
        user_idx = item.get("user_task_index", "?")
        inj_idx = item.get("injection_task_index", "?")
        payload_preview = str(item.get("Attacker Instruction", ""))[:80].replace("\n", " ")

        log(f"[{_ts()}] Entry {idx+1}/{total} | suite={suite} | user={user_idx} | inj={inj_idx}")

        if args.verbose:
            log(f"[{_ts()}]   Payload preview : {payload_preview}...")

        try:
            success = _run_entry(item, args.model_name)
        except Exception as exc:
            log(f"[{_ts()}]   ERROR: {exc}")
            success = False

        log(f"[{_ts()}]   Attack succeeded : {success}")

        suite_key = suite if suite in counts else "dh"
        counts[suite_key]["total"] += 1
        if success:
            counts[suite_key]["success"] += 1

    # ── summary ──────────────────────────────────────────────────────────────
    sep = "═" * 52
    log(f"\n{sep}")

    dh_t = counts["dh"]["total"]
    dh_s = counts["dh"]["success"]
    ds_t = counts["ds"]["total"]
    ds_s = counts["ds"]["success"]
    all_t = dh_t + ds_t
    all_s = dh_s + ds_s

    def pct(num: int, den: int) -> str:
        return f"{100*num/den:.2f}%" if den else "N/A"

    log(f"  Direct Harm (DH)")
    log(f"    Total        : {dh_t}")
    log(f"    ASR          : {pct(dh_s, dh_t)}  ({dh_s}/{dh_t})")
    log("")
    log(f"  Data Stealing (DS — S1)")
    log(f"    Total        : {ds_t}")
    log(f"    ASR          : {pct(ds_s, ds_t)}  ({ds_s}/{ds_t})")
    log("")
    log(f"  Overall")
    log(f"    Total        : {all_t}")
    log(f"    ASR          : {pct(all_s, all_t)}  ({all_s}/{all_t})")
    log(sep)

    log_fh.close()


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Run TopicAttack payloads against InjecAgent")
    p.add_argument(
        "--data_paths",
        nargs="+",
        required=True,
        help="Attack-complete JSON files (output of construct_attack.py)",
    )
    p.add_argument("--model_name", default="gpt-4o-mini", help="Victim LLM")
    p.add_argument(
        "--log_file",
        default="logs/topicattack_injecagent_results.txt",
        help="Output log file path",
    )
    p.add_argument("--verbose", action="store_true", help="Print payload preview per entry")
    return p.parse_args()


if __name__ == "__main__":
    run(parse_args())
